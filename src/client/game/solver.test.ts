import { describe, expect, it } from "vitest";
import type { Grid } from "../types";
import { copyGrid } from "./grid";
import { countSolutions, solveGrid } from "./solver";

const puzzle: Grid = [
  [5, 3, 0, 0, 7, 0, 0, 0, 0],
  [6, 0, 0, 1, 9, 5, 0, 0, 0],
  [0, 9, 8, 0, 0, 0, 0, 6, 0],
  [8, 0, 0, 0, 6, 0, 0, 0, 3],
  [4, 0, 0, 8, 0, 3, 0, 0, 1],
  [7, 0, 0, 0, 2, 0, 0, 0, 6],
  [0, 6, 0, 0, 0, 0, 2, 8, 0],
  [0, 0, 0, 4, 1, 9, 0, 0, 5],
  [0, 0, 0, 0, 8, 0, 0, 7, 9],
];

const solution: Grid = [
  [5, 3, 4, 6, 7, 8, 9, 1, 2],
  [6, 7, 2, 1, 9, 5, 3, 4, 8],
  [1, 9, 8, 3, 4, 2, 5, 6, 7],
  [8, 5, 9, 7, 6, 1, 4, 2, 3],
  [4, 2, 6, 8, 5, 3, 7, 9, 1],
  [7, 1, 3, 9, 2, 4, 8, 5, 6],
  [9, 6, 1, 5, 3, 7, 2, 8, 4],
  [2, 8, 7, 4, 1, 9, 6, 3, 5],
  [3, 4, 5, 2, 8, 6, 1, 7, 9],
];

describe("solver", () => {
  it("solves a valid puzzle", () => {
    const grid = copyGrid(puzzle);
    const solved = solveGrid(grid);

    expect(solved).toBe(true);
    expect(grid).toEqual(solution);
  });

  it("counts a single solution for a nearly complete grid", () => {
    const grid = copyGrid(solution);
    grid[0][0] = 0;

    const count = countSolutions(grid, 2);
    expect(count).toBe(1);
  });
});
